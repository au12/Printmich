"""ICC helpers: an Adobe RGB (1998)-compatible output profile generated on the fly
(so no redistributable-license questions), sRGB bytes, and embedded-profile inspection."""
from __future__ import annotations

import functools
import struct
import tempfile
from pathlib import Path

import numpy as np

D50_ICC = (0.9642, 1.0, 0.8249)
BRADFORD = np.array([[0.8951, 0.2664, -0.1614], [-0.7502, 1.7135, 0.0367], [0.0389, -0.0685, 1.0296]])


def _xy_to_xyz(x: float, y: float) -> np.ndarray:
    return np.array([x / y, 1.0, (1 - x - y) / y])


def _rgb_to_xyz_matrix(primaries: tuple[tuple[float, float], ...], white: tuple[float, float]) -> np.ndarray:
    m = np.column_stack([_xy_to_xyz(*p) for p in primaries])
    s = np.linalg.solve(m, _xy_to_xyz(*white))
    return m * s


def _adapt_to_d50(m: np.ndarray, white_xy: tuple[float, float]) -> np.ndarray:
    src = BRADFORD @ _xy_to_xyz(*white_xy)
    dst = BRADFORD @ np.array(D50_ICC)
    adapt = np.linalg.inv(BRADFORD) @ np.diag(dst / src) @ BRADFORD
    return adapt @ m


def _s15f16(v: float) -> bytes:
    return struct.pack(">i", round(v * 65536))


def _xyz_tag(xyz: np.ndarray | tuple[float, float, float]) -> bytes:
    return b"XYZ " + b"\0" * 4 + b"".join(_s15f16(float(v)) for v in xyz)


def _curv_tag(gamma: float) -> bytes:
    return b"curv" + b"\0" * 4 + struct.pack(">I", 1) + struct.pack(">H", round(gamma * 256))


def _desc_tag(text: str) -> bytes:
    a = text.encode("ascii") + b"\0"
    return (b"desc" + b"\0" * 4 + struct.pack(">I", len(a)) + a + struct.pack(">II", 0, 0)
            + struct.pack(">H", 0) + b"\0" + b"\0" * 67)


def _text_tag(text: str) -> bytes:
    return b"text" + b"\0" * 4 + text.encode("ascii") + b"\0"


def build_matrix_profile(description: str, primaries: tuple[tuple[float, float], ...],
                         white: tuple[float, float], gamma: float) -> bytes:
    m = _adapt_to_d50(_rgb_to_xyz_matrix(primaries, white), white)
    tags = [
        (b"desc", _desc_tag(description)),
        (b"cprt", _text_tag("No copyright, use freely (generated by Printmich)")),
        (b"wtpt", _xyz_tag(D50_ICC)),
        (b"rXYZ", _xyz_tag(m[:, 0])),
        (b"gXYZ", _xyz_tag(m[:, 1])),
        (b"bXYZ", _xyz_tag(m[:, 2])),
        (b"rTRC", _curv_tag(gamma)),
    ]
    shared_trc = {b"gTRC": b"rTRC", b"bTRC": b"rTRC"}
    table_size = 4 + 12 * (len(tags) + len(shared_trc))
    offset = 128 + table_size
    entries, blobs, positions = [], bytearray(), {}
    for sig, data in tags:
        pad = (-len(data)) % 4
        positions[sig] = (offset + len(blobs), len(data))
        entries.append((sig, offset + len(blobs), len(data)))
        blobs += data + b"\0" * pad
    for sig, ref in shared_trc.items():
        entries.append((sig, *positions[ref]))
    table = struct.pack(">I", len(entries)) + b"".join(s + struct.pack(">II", o, n) for s, o, n in entries)
    size = 128 + len(table) + len(blobs)
    hdr = bytearray(128)
    struct.pack_into(">I", hdr, 0, size)
    hdr[8:12] = bytes([2, 0x10, 0, 0])
    hdr[12:16] = b"mntr"
    hdr[16:20] = b"RGB "
    hdr[20:24] = b"XYZ "
    struct.pack_into(">6H", hdr, 24, 2026, 1, 1, 0, 0, 0)
    hdr[36:40] = b"acsp"
    hdr[68:80] = b"".join(_s15f16(v) for v in D50_ICC)
    return bytes(hdr) + table + bytes(blobs)


@functools.lru_cache(maxsize=1)
def adobe_rgb_bytes() -> bytes:
    return build_matrix_profile(
        "Printmich Wide RGB (compatible with Adobe RGB 1998)",
        ((0.64, 0.33), (0.21, 0.71), (0.15, 0.06)), (0.3127, 0.3290), 563 / 256)


_PROFILE_DIR = Path(tempfile.gettempdir()) / "printmich-profiles"


@functools.lru_cache(maxsize=1)
def adobe_rgb_path() -> str:
    _PROFILE_DIR.mkdir(parents=True, exist_ok=True)
    p = _PROFILE_DIR / "PrintmichWideRGB-AdobeRGB1998-compatible.icc"
    if not p.exists() or p.read_bytes() != adobe_rgb_bytes():
        p.write_bytes(adobe_rgb_bytes())
    return str(p)


@functools.lru_cache(maxsize=1)
def srgb_bytes() -> bytes:
    import pyvips
    img = (pyvips.Image.black(1, 1, bands=3) + 128).cast("uchar").copy(interpretation="srgb")
    out = img.icc_transform("srgb", input_profile="srgb")
    return bytes(out.get("icc-profile-data"))


def profile_for_space(space: str) -> str:
    """Value for libvips' output_profile argument."""
    return adobe_rgb_path() if space == "adobe-rgb" else "srgb"


def profile_bytes_for_space(space: str) -> bytes | None:
    if space == "adobe-rgb":
        return adobe_rgb_bytes()
    if space == "srgb":
        return srgb_bytes()
    return None


def profile_description(data: bytes | None) -> str:
    """Best-effort read of an ICC profile's 'desc' tag (v2 textDescription or v4 mluc)."""
    if not data or len(data) < 132:
        return ""
    try:
        count = struct.unpack_from(">I", data, 128)[0]
        for i in range(min(count, 100)):
            sig, off, size = struct.unpack_from(">4sII", data, 132 + 12 * i)
            if sig != b"desc":
                continue
            blob = data[off:off + size]
            if blob[:4] == b"desc":
                n = struct.unpack_from(">I", blob, 8)[0]
                return blob[12:12 + n].split(b"\0", 1)[0].decode("latin-1", "replace")
            if blob[:4] == b"mluc":
                recs = struct.unpack_from(">I", blob, 8)[0]
                if recs:
                    ln, lo = struct.unpack_from(">II", blob, 20)
                    return blob[lo:lo + ln].decode("utf-16-be", "replace")
    except Exception:
        return ""
    return ""


def profile_color_space(data: bytes | None) -> str:
    if not data or len(data) < 20:
        return ""
    return data[16:20].decode("ascii", "replace").strip()


def is_wide_gamut(data: bytes | None) -> bool:
    """True when the embedded profile is an RGB space wider than sRGB (P3, Adobe RGB, ProPhoto …)."""
    if not data or profile_color_space(data) != "RGB":
        return False
    desc = profile_description(data).lower()
    if not desc:
        return False
    if "srgb" in desc or "iec61966" in desc or "iec 61966" in desc:
        return False
    wide_words = ("p3", "adobe", "prophoto", "romm", "2020", "wide", "dci", "display p3", "beta", "ecirgb")
    return any(w in desc for w in wide_words)
